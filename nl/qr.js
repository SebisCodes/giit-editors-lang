/* The content types (payload.js TYPE_NAMES) inside messages. */
const TYPES = {
    Link: 'Link', Text: 'Tekst', WiFi: 'Wifi', Contact: 'Contact', Email: 'E-mail', SMS: 'Sms', Phone: 'Telefoon',
    Location: 'Locatie', Event: 'Afspraak', Crypto: 'Crypto', 'SEPA payment': 'SEPA-betaling', 'Swiss QR bill': 'Zwitserse QR-factuur',
};
/**
 * Translates the text the pattern found (type in the English pattern).
 * @param {string} s - the English text the pattern found.
 * @returns {string} the text in the language.
 */
const translateType = s => TYPES[s] || s;
/* Where a scanned code came from (app.js): a file name, the clipboard or the camera. */
/**
 * Translates the text the pattern found (source in the English pattern).
 * @param {string} s - the English text the pattern found.
 * @returns {string} the text in the language.
 */
const translateSource = s => (s === 'the clipboard' ? 'het klembord' : s === 'the camera' ? 'de camera' : `"${s}"`);
/* What a design key takes (qrdoc.js KEYS hint); lists of values stay as they are. */
/**
 * Translates the text the pattern found (hint in the English pattern).
 * @param {string} h - the English text the pattern found.
 * @returns {string} the text in the language.
 */
function translateHint(h) {
    let m;
    if (h === 'auto or 1 to 40') return 'auto of 1 tot 40';
    if (h === 'auto or 0 to 7') return 'auto of 0 tot 7';
    if (h === '0 to 20 modules') return '0 tot 20 modules';
    if (h === '0 to 360 degrees') return '0 tot 360 graden';
    if (h === '5 to 30 percent') return '5 tot 30 procent';
    if ((m = /^a color like (#\w+), or transparent$/.exec(h))) return `een kleur zoals ${m[1]}, of transparent`;
    if ((m = /^a color like (#\w+)$/.exec(h))) return `een kleur zoals ${m[1]}`;
    if ((m = /^(.+) or a picture as (.+)$/.exec(h))) return `${m[1]} of een afbeelding als ${m[2]}`;
    return h;
}

