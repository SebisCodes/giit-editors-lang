/**
 * Translates the text the pattern found (hint in the English pattern).
 * @param {string} h - the English text the pattern found.
 * @returns {string} the text in the language.
 */
function translateHint(h) {
    const fixed = {
        'auto or 1 to 40': 'auto または 1～40',
        'auto or 0 to 7': 'auto または 0～7',
        '0 to 20 modules': '0～20 モジュール',
        'a color like #1d2b53': '#1d2b53 のような色',
        '0 to 360 degrees': '0～360 度',
        'a color like #ffffff, or transparent': '#ffffff のような色、または transparent',
        '5 to 30 percent': '5～30 %',
    }[h];
    if (fixed) return fixed;
    const m = /^none, (.+) or a picture as (data:.+)$/.exec(h);
    return m ? `none、${m[1]}、または画像 (${m[2]})` : h;
}

