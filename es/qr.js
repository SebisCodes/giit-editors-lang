    Link: 'Enlace', Text: 'Texto', WiFi: 'Wi-Fi', Contact: 'Contacto', Email: 'Correo electrónico', SMS: 'SMS', Phone: 'Teléfono',
    Location: 'Ubicación', Event: 'Evento', Crypto: 'Cripto', 'SEPA payment': 'Pago SEPA', 'Swiss QR bill': 'Factura QR suiza',
