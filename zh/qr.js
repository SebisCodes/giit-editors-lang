/**
 * Translates the text the pattern found (hint in the English pattern).
 * @param {string} h - the English text the pattern found.
 * @returns {string} the text in the language.
 */
function translateHint(h) {
    const fixed = {
        'auto or 1 to 40': 'auto 或 1 到 40',
        'auto or 0 to 7': 'auto 或 0 到 7',
        '0 to 20 modules': '0 到 20 个模块',
        'a color like #1d2b53': '颜色，例如 #1d2b53',
        '0 to 360 degrees': '0 到 360 度',
        'a color like #ffffff, or transparent': '颜色，例如 #ffffff，或 transparent',
        '5 to 30 percent': '5 到 30 %',
    }[h];
    if (fixed) return fixed;
    const m = /^none, (.+) or a picture as (data:.+)$/.exec(h);
    return m ? `none、${m[1]}，或图片 ${m[2]}` : h;
}

