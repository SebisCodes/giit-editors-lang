const TYPES = {
    Link: 'Link', Text: 'Texto', WiFi: 'Wi-Fi', Contact: 'Contato', Email: 'E-mail', SMS: 'SMS', Phone: 'Telefone',
    Location: 'Localização', Event: 'Evento', Crypto: 'Cripto', 'SEPA payment': 'Pagamento SEPA', 'Swiss QR bill': 'Fatura QR suíça',
};
/**
 * Translates the text the pattern found (type in the English pattern).
 * @param {string} s - the English text the pattern found.
 * @returns {string} the text in the language.
 */
const translateType = s => TYPES[s] || s;
/* Where a scanned code came from (app.js): a file name, the clipboard or the camera. */
/**
 * Translates the text the pattern found (source in the English pattern).
 * @param {string} s - the English text the pattern found.
 * @returns {string} the text in the language.
 */
const translateSource = s => (s === 'the clipboard' ? 'da área de transferência' : s === 'the camera' ? 'da câmera' : `de "${s}"`);
/* What a design key takes (qrdoc.js KEYS hint); lists of values stay as they are. */
/**
 * Translates the text the pattern found (hint in the English pattern).
 * @param {string} h - the English text the pattern found.
 * @returns {string} the text in the language.
 */
function translateHint(h) {
    let m;
    if (h === 'auto or 1 to 40') return 'auto ou de 1 a 40';
    if (h === 'auto or 0 to 7') return 'auto ou de 0 a 7';
    if (h === '0 to 20 modules') return 'de 0 a 20 módulos';
    if (h === '0 to 360 degrees') return 'de 0 a 360 graus';
    if (h === '5 to 30 percent') return 'de 5 a 30 por cento';
    if ((m = /^a color like (#\w+), or transparent$/.exec(h))) return `uma cor como ${m[1]}, ou transparent`;
    if ((m = /^a color like (#\w+)$/.exec(h))) return `uma cor como ${m[1]}`;
    if ((m = /^(.+) or a picture as (.+)$/.exec(h))) return `${m[1]} ou uma imagem como ${m[2]}`;
    return h;
}

